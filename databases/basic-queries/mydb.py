
class MemoryScan(object):
    """
    Yield all records from the given "table" in memory.

    This is really just for testing... in the future our scan nodes
    will read from disk.
    """
    def __init__(self, table):
        self.table = table
        self.idx = 0

    def next(self):
        if self.idx >= len(self.table):
            return None

        x = self.table[self.idx]
        self.idx += 1
        return x


class Projection(object):
    """
    Map the child records using the given map function, e.g. to return a subset
    of the fields.
    """
    def __init__(self, proj):
        self.proj = proj
        self.child = None

    def next(self):
        tuple = self.child.next()
        if tuple == None:
            return None
        return self.proj(tuple)
        


class Selection(object):
    """
    Filter the child records using the given predicate function.

    Yes it's confusing to call this "selection" as it's unrelated to SELECT in
    SQL, and is more like the WHERE clause. We keep the naming to be consistent
    with the literature.
    """
    def __init__(self, predicate):
        self.predicate = predicate
        self.child = None

    def next(self):
        while True:
            tuple = self.child.next()
            if tuple == None:
                return None
            if self.predicate(tuple):
                return tuple


class Limit(object):
    """
    Return only as many as the limit, then stop.
    Optional offset as the second argument.
    """
    def __init__(self, n, o = 0):
        self.limit = n
        self.offset = o
        self.returned = 0
        self.child = None

    def next(self):
        while self.offset > 0:
            val = self.child.next();
            if val == None:
                return None
            self.offset -= 1;

        if self.limit == self.returned:
            return None

        self.returned += 1
        return self.child.next()

class Sort(object):
    """
    Sort based on the given key function
    """
    def __init__(self, key, desc=False):
        self.key = key
        self.desc = desc
        self.child = None
        self.data = None
        self.idx = 0

    def get_data(self):
        self.data = []
        while t := self.child.next():
            self.data.append(t)
        self.data.sort(key=self.key, reverse=self.desc)

    def next(self):
        if self.data == None:
            self.get_data()

        if self.idx > len(self.data):
            return None

        t = self.data[self.idx]
        self.idx += 1
        return t

class Sum(object):
    """
    Sum the given column of the table
    """
    def __init__(self, select_col):
        self.select_col = select_col
        self.sum = 0
        self.child = None
        self.finished = False

    def next(self):
        if self.finished:
            return None

        while t := self.child.next():
            self.sum += self.select_col(t)

        self.finished = True
        return (self.sum,)

class Avg(object):
    """
    Sum the given column of the table
    """
    def __init__(self, select_col):
        self.select_col = select_col
        self.sum = 0
        self.count = 0
        self.child = None
        self.finished = False

    def next(self):
        if self.finished:
            return None

        while t := self.child.next():
            self.sum += self.select_col(t)
            self.count += 1

        self.finished = True
        return (self.sum / self.count,)

def Q(*nodes):
    """
    Construct a linked list of executor nodes from the given arguments,
    starting with a root node, and adding references to each child
    """
    ns = iter(nodes)
    parent = root = next(ns)
    for n in ns:
        parent.child = n
        parent = n
    return root


def run(q):
    """
    Run the given query to completion by calling `next` on the (presumed) root
    """
    while True:
        x = q.next()
        if x is None:
            break
        yield x


